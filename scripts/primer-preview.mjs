// Render the environment primer and arrival labels from the built packages, for owner review
// (Phase 8). Loads the real core, life, memory and adapters into a bare Cordis context with a
// fake session host; nothing connects anywhere (QQ points at a closed port, Bilibili's fetch
// is stubbed). Usage: pnpm -r build && node scripts/primer-preview.mjs [out.md]
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'

const root = new URL('..', import.meta.url).pathname
const lib = (pkg, file = 'index.js') => import(pathToFileURL(join(root, 'packages', pkg, 'lib', file)).href)
const dep = name => import(pathToFileURL(join(root, 'packages/anima-core/node_modules', name, 'lib/index.js')).href)

const { Context } = await dep('@deepseek-ai/cordis')
const SystemPrompt = (await dep('@deepseek-ai/dsh-system-prompt')).default
const Tools = (await dep('@deepseek-ai/dsh-tools')).default
const core = await lib('anima-core')
const life = await lib('anima-life')
const memory = await lib('anima-memory')
const local = await lib('anima-adapter-local')
const qq = await lib('anima-adapter-qq')
const bili = await lib('anima-adapter-bili')
const guard = await lib('anima-guard')

const delivered = []
class Host {
  sessions = new Map()
  async resolve(id) { return this.sessions.get(id) }
  async create(id) { this.sessions.set(id, { id }); return id }
  isArchived() { return false }
  rename() {}
  async deliver(agent, text) { delivered.push({ id: agent.id, wake: true, text }) }
  async inject(agent, text) { delivered.push({ id: agent.id, wake: false, text }) }
  steer(agent, text) { delivered.push({ id: agent.id, wake: false, text }) }
  selectModel() {}
  isBusy() { return false }
}

const dataDir = mkdtempSync(join(tmpdir(), 'anima-primer-'))
const ctx = new Context()
ctx.logger = { info() {}, warn() {}, debug() {}, error() {} }
await ctx.plugin(SystemPrompt)
await ctx.plugin(Tools)
await ctx.plugin(core, { dataDir, characterId: 'preview', name: '小鲸鱼', clock: { speed: 1, start: '2026-11-12T10:00' } })
await ctx.plugin(life.AnimaLife, { host: new Host(), config: {} })
// The guard is outside the persona; loaded, it adds its owner rules to "this place".
await ctx.plugin(guard, {})
await ctx.plugin(memory, {})
await ctx.plugin(local, {})
await ctx.plugin(qq, {
  url: 'ws://127.0.0.1:9', accessToken: 'x', account: '10001', owner: '20002', ownerName: 'Sam',
  allow: { users: [{ id: '30003', name: '测试号' }], groups: [{ id: '40004', name: '测试群' }] },
})
await ctx.plugin(bili, { client: { fetch: async () => new Response('{"code":-101,"data":{}}', { headers: { 'content-type': 'application/json' } }) } })
await new Promise(resolve => setTimeout(resolve, 100))

const A = ctx.anima
const L = ctx.animaLife
const channel = key => L.router.channel(key)
const keys = {
  qqOwner: 'qq:10001:private:20002',
  qqFriend: 'qq:10001:private:30003',
  qqGroup: 'qq:10001:group:40004',
  local: 'local:owner:private:owner',
}
const constitution = '（宪法：主人写的 constitution.md 原文放在这里，此处省略）'
const sessionOf = key => L.router.conversationId(channel(key))
const primer = (id, kind) => core.primerText(constitution, A.placeFacts(id, kind))

const out = []
const section = (title, text) => out.push(`## ${title}\n\n\`\`\`text\n${text.trimEnd()}\n\`\`\`\n`)
out.push('# Phase 8 primer preview\n')
out.push('Generated by `scripts/primer-preview.mjs` from the built packages (real core, life, memory, local, QQ and Bilibili adapters; default config; a QQ allowlist shaped like formal-1 with placeholder account ids). The constitution is left out. Tool descriptions, the Self situation report, the `[memory]` block and the self-model digest stay English this phase.\n')
section('QQ private chat with the owner (conversation)', primer(sessionOf(keys.qqOwner), 'conversation'))
section('QQ private chat with someone else: "此处" only', core.placeText(A.placeFacts(sessionOf(keys.qqFriend), 'conversation')))
section('QQ group: "此处" only', core.placeText(A.placeFacts(sessionOf(keys.qqGroup), 'conversation')))
section('Local chat with the owner: "此处" only', core.placeText(A.placeFacts(sessionOf(keys.local), 'conversation')))
section('Self (constitution, her world, this place, rules)', primer(L.router.selfId, 'self'))
for (const kind of ['triage', 'group-triage', 'consolidation', 'viewing']) {
  section(`${kind}: "此处" and rules`, `${core.placeText(A.placeFacts(undefined, kind))}\n\n${core.SESSION_RULES[kind]}`)
}

// Arrival labels, delivered through the real router (with the clock stamp and the answer line).
const sam = { platformUserId: '20002', displayName: 'Sam', isOwner: true }
const friend = { platformUserId: '30003', displayName: '测试号', isOwner: false }
const bob = { platformUserId: '2002', displayName: 'Bob', isOwner: false }
const route = async (stimulus, wake) => {
  delivered.length = 0
  await L.router.deliver(stimulus, undefined, wake)
  return delivered.map(d => `${d.wake ? '' : '(context, no wake) '}${d.text}`).join('\n')
}
const ts = A.clock.now()
const labels = []
labels.push(['Private message from the owner', await route({ type: 'message', channel: channel(keys.qqOwner), sender: sam, text: '在吗', messageId: '101', ts })])
labels.push(['Private message from someone else', await route({ type: 'message', channel: channel(keys.qqFriend), sender: friend, text: '明天去吗', messageId: '102', ts })])
labels.push(['Poke (private)', await route({ type: 'message', channel: channel(keys.qqOwner), sender: sam, text: '[戳了戳你]', ts })])
labels.push(['Group: @ or reply to her', await route({ type: 'message', channel: channel(keys.qqGroup), sender: bob, text: '@小鲸鱼 你也来吗', messageId: '201', addressed: true, ts })])
labels.push(['Group: earlier message as context', await route({ type: 'message', channel: channel(keys.qqGroup), sender: bob, text: '周末火锅', messageId: '200', ts }, false)])
labels.push(['Group: woken by triage', await route({ type: 'message', channel: channel(keys.qqGroup), sender: bob, text: '有人推荐火锅店吗', messageId: '202', via: { kind: 'triage', reason: '我知道一家很好吃的' }, ts }, true)])
labels.push(['Group: attention window after she spoke', await route({ type: 'message', channel: channel(keys.qqGroup), sender: bob, text: '哈哈真的吗', messageId: '203', via: { kind: 'attention' }, ts }, true)])
labels.push(['Intent from Self', await route({ type: 'intent', channel: channel(keys.qqOwner), intentId: 'i7', intent: '问问他今天考试怎么样', context: '他昨天说今天有考试', heldSeconds: ctx.animaGuard.config.outbox.delaySeconds, ts })])
labels.push(['Channel event (only into an existing session)', await route({ type: 'channel-event', channel: channel(keys.qqOwner), text: 'Sam recalled a message (msg 99).', ts })])
labels.push(['Local chat message', await route({ type: 'message', channel: channel(keys.local), sender: { platformUserId: 'owner', displayName: 'Sam', isOwner: true }, text: 'hello', ts })])
labels.push(['Close reminder (1st of 2, with her unsent text)', life.reminderText('qq_say', '在的在的，怎么了？', 1, 2)])
labels.push(['Close reminder (no text)', life.reminderText('qq_say', '', 2, 2)])
out.push('## Arrival labels\n')
for (const [title, text] of labels) out.push(`### ${title}\n\n\`\`\`text\n${text}\n\`\`\`\n`)

const target = process.argv[2]
if (target === undefined) console.log(out.join('\n'))
else writeFileSync(target, out.join('\n'))
await ctx.fiber.dispose?.()
rmSync(dataDir, { recursive: true, force: true })
process.exit(0)
