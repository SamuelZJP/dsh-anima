// Write the --patch overlay of the scripted reliability check (Phases 8 and 9) into its own data dir.
// Nothing under ~/.dsh changes. Usage: node scripts/reliability/make-overlay.mjs [--constitution <file>]
// Boot: pnpm dsh --profile anima-dev --patch ~/.anima/<run>/check.patch.yml --no-open (run: ANIMA_CHECK, default check-p9)
import { copyFileSync, existsSync, mkdirSync, writeFileSync } from 'node:fs'
import { homedir } from 'node:os'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { ACCOUNT, CHARACTER, CHECK_DIR, GROUPS, OWNER, PORT, USERS } from './cast.mjs'

// Default quotas, except the global ceiling: ~210 turns in ~1 h are several days of her calls,
// and the check measures how turns close, not the daily ceiling.
const { DEFAULT_QUOTAS } = await import(new URL('../../packages/anima-core/lib/config.js', import.meta.url).href)
const quotas = DEFAULT_QUOTAS.map(rule => rule.per === 'global' && rule.behavior === undefined && rule.effect === undefined && rule.platform === undefined ? { ...rule, limit: 2000 } : rule)

const dir = CHECK_DIR.replace(/^~/, homedir())
mkdirSync(dir, { recursive: true })
const at = process.argv.indexOf('--constitution')
const constitution = at > 0 ? process.argv[at + 1] : undefined
if (constitution !== undefined && !existsSync(join(dir, 'constitution.md'))) copyFileSync(constitution, join(dir, 'constitution.md'))

const today = new Date()
const pad = n => String(n).padStart(2, '0')
const start = `${today.getFullYear()}-${pad(today.getMonth() + 1)}-${pad(today.getDate())}T10:00`
const check = fileURLToPath(new URL('./check.mjs', import.meta.url))
const yaml = `# Scripted reliability check (DESIGN §14). Own character and data dir; QQ points at the
# fake OneBot server that the check row runs in-process. Generated by scripts/reliability/make-overlay.mjs.
- id: anima-core
  config:
    characterId: ${CHARACTER}
    name: 小鲸鱼
    dataDir: ${CHECK_DIR}
    clock: { speed: 1, start: '${start}' }
    # Scripted intents come from the check; Self starts none of its own.
    initiate: { perDay: 0 }
    modes:
      day: { tokenBudget: 3000000 }
    quotas:
${quotas.map(rule => `      - ${JSON.stringify(rule)}`).join('\n')}
- id: anima-life
  config:
    groupTriage: { windowSeconds: 10 }
    outbox: { delaySeconds: 5 }
- id: anima-adapter-qq
  disabled: false
  config:
    url: ws://127.0.0.1:${PORT}
    accessToken: check-p8
    account: '${ACCOUNT}'
    owner: '${OWNER.id}'
    ownerName: ${OWNER.name}
    allow:
      users:
${USERS.map(user => `        - { id: '${user.id}', name: ${user.name} }`).join('\n')}
      groups:
${GROUPS.map(group => `        - { id: '${group.id}', name: ${group.name} }`).join('\n')}
- insert:
    - id: anima-reliability-check
      name: ${check}
      config:
        port: ${PORT}
        targetTurns: 210
`
writeFileSync(join(dir, 'check.patch.yml'), yaml)
console.log(join(dir, 'check.patch.yml'))
